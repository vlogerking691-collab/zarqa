/*
# Create orders table for Zarqa Traders COD checkout

1. New Tables
- `orders`
  - `id` (uuid, primary key, generated by the storefront so it can serve as the order reference)
  - `customer_name` (text, boutique or customer name)
  - `phone` (text, WhatsApp number)
  - `city` (text)
  - `address` (text, full delivery address)
  - `notes` (text, optional order notes)
  - `items` (jsonb, list of ordered sets with quantity and unit price)
  - `subtotal` (integer, PKR)
  - `payment_method` (text, always cash on delivery for now)
  - `status` (text, defaults to 'pending')
  - `created_at` (timestamptz)

2. Security
- Enable RLS on `orders`.
- Anonymous visitors (no sign-in in this store) may only INSERT orders, and only when every field passes length and format checks.
- No SELECT, UPDATE or DELETE is granted to public roles, so customer details cannot be read back through the public API.

3. Notes
- Order records are reviewed by the business via the Supabase dashboard.
*/

CREATE TABLE IF NOT EXISTS orders (
  id uuid PRIMARY KEY,
  customer_name text NOT NULL CHECK (char_length(customer_name) BETWEEN 2 AND 120),
  phone text NOT NULL CHECK (char_length(phone) BETWEEN 7 AND 25),
  city text NOT NULL CHECK (char_length(city) BETWEEN 2 AND 80),
  address text NOT NULL CHECK (char_length(address) BETWEEN 5 AND 400),
  notes text NOT NULL DEFAULT '' CHECK (char_length(notes) <= 1000),
  items jsonb NOT NULL CHECK (jsonb_typeof(items) = 'array' AND jsonb_array_length(items) BETWEEN 1 AND 100),
  subtotal integer NOT NULL CHECK (subtotal > 0),
  payment_method text NOT NULL DEFAULT 'cod' CHECK (payment_method = 'cod'),
  status text NOT NULL DEFAULT 'pending',
  created_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE orders ENABLE ROW LEVEL SECURITY;

GRANT INSERT ON orders TO anon, authenticated;

DROP POLICY IF EXISTS "public_insert_cod_orders" ON orders;
CREATE POLICY "public_insert_cod_orders" ON orders FOR INSERT
  TO anon, authenticated
  WITH CHECK (
    status = 'pending'
    AND payment_method = 'cod'
    AND char_length(customer_name) BETWEEN 2 AND 120
    AND char_length(phone) BETWEEN 7 AND 25
    AND char_length(city) BETWEEN 2 AND 80
    AND char_length(address) BETWEEN 5 AND 400
  );
